import { ouvrir, audit, largeur, connexion, base, cap } from './lib.mjs';
const { b, p } = await ouvrir();
await connexion(p, 'demo', 'cam');
await p.goto(base + '/formulaires.html'); await p.waitForSelector('#liste li');
console.log((await p.$$eval('#liste li', l => l.map(x => x.innerText.replace(/\n+/g,' | ')))).join('\n'));
await audit(p, 'formulaires'); await largeur(p, 'formulaires');
await cap(p, 'apercu-formulaires-bureau.png');
await p.click('a:has-text("Reprendre")'); await p.waitForSelector('#vue:not([hidden])');
await audit(p, 'pays-1'); await largeur(p, 'pays-1');
// ajout pays hors liste, sans justification
await p.selectOption('#pays-select', 'Russie'); await p.click('#pays-ajouter');
console.log('hors liste:', (await p.textContent('#hors-liste')).trim());
await p.click('#btn-suivant');
console.log('erreurs:', (await p.textContent('#erreurs')).trim());
await cap(p, 'apercu-pays-erreurs.png');
await p.fill('#justification', 'Un client historique en Russie.'); await p.click('#btn-suivant');
await p.waitForSelector('[data-etape="2"]:not([hidden])');
console.log('préremplis visibles:', await p.$eval('#aide-partExport', e => !e.hidden), await p.$eval('#aide-nbAcheteurs', e => !e.hidden));
await audit(p, 'pays-2'); await largeur(p, 'pays-2');
await p.click('#btn-suivant'); console.log('erreurs étape 2:', (await p.textContent('#erreurs')).trim());
await p.check('#devise-EUR'); await p.fill('#partExport', '40');
console.log('préremplis après modif:', await p.$eval('#aide-partExport', e => !e.hidden));
await p.click('#btn-brouillon'); console.log('brouillon:', await p.textContent('#msg-brouillon'));
await p.click('#btn-suivant'); await p.waitForSelector('[data-etape="3"]:not([hidden])');
await audit(p, 'pays-3'); await largeur(p, 'pays-3');
await cap(p, 'apercu-pays-recap.png');
await p.click('#btn-suivant'); await p.waitForSelector('#bandeau-soumis:not([hidden])');
console.log('soumis:', await p.textContent('#bandeau-soumis'), '| boutons modifier:', await p.$$eval('#recap button', x => x.length));
await audit(p, 'pays-soumis');
await p.reload(); await p.waitForSelector('#bandeau-soumis:not([hidden])'); console.log('rechargé:', (await p.textContent('#bandeau-soumis')).trim().slice(0, 40));
console.log('erreurs console:', p.errs);
await b.close();
